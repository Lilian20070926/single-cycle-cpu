`timescale 1ns/1ps
//------------------------------------------------------------------
// signext: 16 -> 32 位符号扩展
//   这个太简单了，直接给你当参考实现，照着这个风格写别的模块就行。
//------------------------------------------------------------------
module signext (
    input  wire [15:0] imm16,
    output wire [31:0] imm32
);

    assign imm32 = {{16{imm16[15]}}, imm16};

endmodule

`timescale 1ns/1ps//------------------------------------------------------------------
// imem: 指令存储器
//   tb 会在第一个时钟沿之前用层次引用往 mem 里 $readmemh，
//   所以数组名必须叫 mem，别改。
//------------------------------------------------------------------
module imem (
    input  wire [31:0] addr,      // 字节地址
    output wire [31:0] instr
);

    // 256 个字 = 1KB，够放 256 条指令
    reg [31:0] mem [0:255];

    // TODO: 组合读
    //       字节地址 -> 字索引，右移 2 位
    //       只有 256 个字，所以取 addr[9:2]
assign instr = mem[addr[9:2]];
endmodule
